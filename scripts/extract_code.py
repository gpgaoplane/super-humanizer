class ExtractError(Exception):
    pass


def language_of(path):

    return _LANGUAGES.get(PurePath(path).suffix.lower())


def encoding_of(data):


    try:
        encoding = tokenize.detect_encoding(io.BytesIO(data).readline)[0]
    except SyntaxError as error:
        raise ExtractError(
            f"cannot decode the file as utf-8 or the encoding its cookie names: {error.msg}"
        ) from error
    try:
        data.decode(encoding)
    except UnicodeDecodeError as error:
        raise ExtractError(
            f"cannot decode the file as {encoding}: {error.reason} at byte {error.start}"
        ) from error
    return encoding


def _parse(source):

    with warnings.catch_warnings():
        warnings.simplefilter("ignore", SyntaxWarning)
        return ast.parse(source)


def _reads_as_prose(s):




    if isinstance(s, ast.Expr):
        value = s.value
        return (isinstance(value, (ast.Name, ast.Constant))
                or isinstance(value, ast.UnaryOp) and isinstance(value.operand, ast.Name)
                or isinstance(value, (ast.Await, ast.Yield)) and isinstance(value.value, ast.Name))
    return (isinstance(s, ast.AnnAssign) and s.value is None
            or isinstance(s, ast.Return) and isinstance(s.value, ast.Name)
            or isinstance(s, ast.Delete) and all(isinstance(t, ast.Name) for t in s.targets)
            or isinstance(s, ast.Assert) and isinstance(s.test, ast.Name) and s.msg is None)


def _is_code(source):

    try:
        body = _parse(source).body
    except (SyntaxError, ValueError):
        return False
    return any(not _reads_as_prose(s) for s in body)


def _is_skipped(comment, row):

    if row == 1 and comment.startswith("#!"):
        return True
    if row <= 2 and _COOKIE.match(comment):
        return True
    if _DIRECTIVE.match(comment[1:].lstrip()):
        return True
    return _is_code(_MARKER.sub("", comment, count=1).strip())


def _string_class(prefix, inner):


    if _KEY_SHAPE.fullmatch(inner):
        return "C145"
    if "f" in prefix.lower() or "b" in prefix.lower():
        return None
    if len([w for w in inner.split(" ") if w]) < 4 or not any(c.isalpha() for c in inner):
        return None
    if ("{" in inner and "}" in inner) or any(mark in inner for mark in _FORMAT_MARKS):
        return None
    if _OTHER_ESCAPE.search(inner) or "://" in inner:
        return None
    if ("/" in inner or "\\" in inner) and " " not in inner:
        return None
    return "prose"


def _render(text, indent, closing, newline):



    lines = text.split("\n")
    body = lines[0] + "".join(newline + (indent + line if line else "") for line in lines[1:])
    return body + (newline + indent if closing else "")


def _fit(lines, indent):

    closing = len(lines) > 1 and lines[-1] == indent
    body = lines[1:-1] if closing else lines[1:]
    return closing, "\n".join([lines[0]] + [line[len(indent):] if line.startswith(indent)
                                            else line for line in body])


def _layout(raw, dedent, opening=""):











    lines = _BREAK.split(raw)
    newline = "\r\n" if "\r\n" in raw else "\n"
    candidates = [""]
    if dedent:
        candidates = [opening, ""]
        margins = [line[:len(line) - len(line.lstrip(" \t"))] for line in lines[1:]
                   if line.strip()]
        if len(lines) > 1 and not lines[-1].strip():
            margins.append(lines[-1])
        if margins:
            candidates.insert(0, os.path.commonprefix(margins))
    for indent in candidates:
        closing, text = _fit(lines, indent)
        if _render(text, indent, closing, newline) == raw:
            break
    return indent, closing, text


def _surface(first, last):
    return f"line {first}" if first == last else f"lines {first} to {last}"


def _refusal(error):

    if isinstance(error, tokenize.TokenError):
        return f"{error.args[0]} at line {error.args[1][0]}"
    return f"{error.msg} at line {error.lineno}"


def _module_statements(body):

    for node in body:
        yield node
        if isinstance(node, (ast.If, ast.Try, ast.With)):
            for field in ("body", "orelse", "finalbody"):
                yield from _module_statements(getattr(node, field, []))
            for handler in getattr(node, "handlers", []):
                yield from _module_statements(handler.body)


def _is_all(node):
    return isinstance(node, ast.Name) and node.id == "__all__"


def _strings(node):

    if not isinstance(node, (ast.List, ast.Tuple)):
        return []
    return [e.value for e in node.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]


def _public_names(module):



    names = []
    for node in _module_statements(module.body):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if not node.name.startswith("_"):
                names.append(node.name)
        elif isinstance(node, (ast.Assign, ast.AugAssign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            if any(_is_all(t) for t in targets):
                names.extend(_strings(node.value))
        elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            func, args = node.value.func, node.value.args
            if (isinstance(func, ast.Attribute) and func.attr == "extend" and _is_all(func.value)
                    and len(args) == 1):
                names.extend(_strings(args[0]))
    return list(dict.fromkeys(names))


def _docstring_rows(module):

    rows = {}
    for node in ast.walk(module):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            first = node.body[0] if node.body else None
            if (isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant)
                    and isinstance(first.value.value, str)):
                for row in range(first.lineno, first.end_lineno + 1):
                    rows[row] = first.lineno
    return rows


def _comment_units(comments, code_rows, lines, offset):






    groups = []
    for token in comments:
        row = token.start[0]
        if _is_skipped(token.string, row):
            continue
        marker = _MARKER.match(token.string).group(0)
        rest = token.string[len(marker):]
        prefix = marker + (" " if rest.startswith(" ") and rest.strip() else "")
        line = lines[row - 1]
        entry = (token, line[:len(line) - len(line.lstrip(" \t\f"))], prefix,
                 token.string[len(prefix):])
        trailing = row in code_rows
        if (trailing or not groups or groups[-1][1]
                or groups[-1][0][-1][0].start[0] != row - 1):
            groups.append(([entry], trailing))
        else:
            groups[-1][0].append(entry)
    first_block = next((entries for entries, trailing in groups if not trailing), None)
    pending = []
    for entries, _ in groups:
        body = "\n".join(entry[3] for entry in entries)
        license_header = entries is first_block and any(word in body for word in _LICENSE)
        pending.append((offset(entries[0][0].start), offset(entries[-1][0].end), "comment",
                        entries[0][0].start[0], entries[-1][0].start[0], body,
                        {"kind": "comment", "lines": [(e[1], e[2]) for e in entries]},
                        "C147" if license_header else None))
    return pending


def _string_units(text, lines, strings, positions, fixture, offset, pending, records):



    tag = "C148" if fixture else None
    groups = {}
    for token in strings:
        prefix, quote = _STRING_HEAD.match(token.string).groups()
        start = offset(token.start) + len(prefix) + len(quote)
        end = offset(token.end) - len(quote)
        if token.start[0] in positions:
            groups.setdefault(positions[token.start[0]], []).append(
                (token, prefix, quote, start, end))
            continue
        kind = _string_class(prefix, text[start:end])
        if kind == "C145":
            records.append((None, start, end, "C145"))
        if kind == "prose":
            indent, closing, body = _layout(text[start:end], dedent=False)
            pending.append((start, end, "prose_string", token.start[0], token.end[0], body,
                            {"kind": "prose_string", "indent": indent, "quote": quote,
                             "prefix": prefix.lower(), "closing_on_own_line": closing}, tag))
        elif fixture:
            records.append((None, start, end, "C148"))
    concatenated = None
    for first, group in groups.items():
        if len(group) > 1:
            concatenated = first if concatenated is None else concatenated
            if fixture:
                records.extend((None, start, end, "C148") for _, _, _, start, end in group)
            continue
        token, prefix, quote, start, end = group[0]
        line = lines[token.start[0] - 1]
        indent, closing, body = _layout(text[start:end], dedent=True,
                                        opening=line[:len(line) - len(line.lstrip(" \t"))])
        pending.append((start, end, "docstring", token.start[0], token.end[0], body,
                        {"kind": "docstring", "indent": indent, "quote": quote,
                         "prefix": prefix.lower(), "closing_on_own_line": closing}, tag))
    return concatenated


def extract_text(text, path, newline="\n"):







    language = language_of(path)
    if language is None:
        raise ExtractError("no handler for this file type")
    if language != "python":
        return _script_text(text, path, newline)
    document = Document(path=path, format=FORMAT, units=[], cannot_see=list(CANNOT_SEE),
                        encoding="utf-8", newline=newline)
    try:
        tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, SyntaxError) as error:
        document.cannot_see.append(
            f"{path}: tokenize refused the file, {_refusal(error)}, so nothing in it was read")
        return document
    stray = re.search(r"\r(?!\n)", text)
    if stray:
        module = None
        row = text.count("\n", 0, stray.start()) + 1
        document.cannot_see.append(
            f"{path}: a lone CR line break at line {row}, which ast counts as a line end and "
            "tokenize does not, so its docstrings and strings were not read")
    else:
        try:
            module = _parse(text)
        except (SyntaxError, ValueError) as error:
            module = None
            document.cannot_see.append(
                f"{path}: ast refused the file, {_refusal(error)}, so its docstrings and "
                "strings were not read")

    starts = [0] + [m.end() for m in re.finditer("\n", text)]
    lines = text.split("\n")

    def offset(position):
        return starts[position[0] - 1] + position[1]

    posix = "/" + str(path).replace("\\", "/").lstrip("/")
    skipped = (any(d in posix for d in _SKIPPED_DIRS) or posix.endswith(".min.js")
               or any(p.match(lines[0].rstrip("\r")) for p in _GENERATED))
    document.skipped = skipped
    fixture = "/fixtures/" in posix or posix.endswith("/conftest.py")

    code_rows, comments, strings = set(), [], []
    for token in tokens:
        if token.type == tokenize.COMMENT:
            comments.append(token)
        elif token.type not in _TRIVIA:
            code_rows.update(range(token.start[0], token.end[0] + 1))
            if token.type == tokenize.STRING:
                strings.append(token)

    pending = _comment_units(comments, code_rows, lines, offset)
    records = []
    if module is not None:
        document.protected_names = _public_names(module)
        concatenated = _string_units(text, lines, strings, _docstring_rows(module), fixture,
                                     offset, pending, records)
        if concatenated is not None:
            document.cannot_see.append(
                f"{path}: an implicit concatenation in docstring position at line "
                f"{concatenated}, which is read as no docstring")
    return _finish(document, text, path, pending, records, skipped)


def _finish(document, text, path, pending, records, skipped):



    pending.sort(key=lambda p: p[0])
    for start, end, _, first, *_ in pending:
        span = text[start:end]
        if "\r\n" in span and "\n" in span.replace("\r\n", ""):
            document.cannot_see.append(
                f"{path}: mixed line ends, CRLF and LF, inside the unit at line {first}, so "
                "nothing in the file was read")
            return document
    if skipped:
        document.cannot_see.append(
            f"{path}: a generated or vendored file, skipped under C146, so no unit in it weighs")
    for number, (start, end, kind, first, last, body, frame, tag) in enumerate(pending, start=1):
        unit_id = f"u{number:04d}"
        document.units.append(Unit(
            id=unit_id, kind=kind, surface=_surface(first, last), text=body,
            locator={"start": start, "end": end}, weighs=not skipped and tag is None,
            frame=frame))
        if tag is not None:
            records.append((unit_id, start, end, tag))
    document.protected = sorted(records, key=lambda r: r[1])
    return document






class Script:









    def __init__(self, parser, text, data):
        self.parser = parser
        self.root = parser.parse(data).root_node
        self._chars = None
        if len(data) != len(text):
            self._chars = [0] * (len(data) + 1)
            position = 0
            for index, char in enumerate(text):
                self._chars[position] = index
                position += len(char.encode("utf-8"))
            self._chars[position] = len(text)

    def offset(self, byte):
        return byte if self._chars is None else self._chars[byte]


def parse_script(text, path):




    try:
        from tree_sitter_language_pack import get_parser
    except ImportError:
        return None, (f"{path}: the package tree-sitter-language-pack is not installed, so "
                      "nothing in the file was read")
    grammar = _GRAMMARS[PurePath(path).suffix.lower()]
    try:
        parser = get_parser(grammar)
    except Exception as error:
        return None, (f"{path}: the {grammar} grammar did not load, {type(error).__name__}: "
                      f"{error}, so nothing in the file was read")
    return Script(parser, text, text.encode("utf-8")), None


def walk(node):

    stack = [node]
    while stack:
        current = stack.pop()
        yield current
        stack.extend(reversed(current.children))


def _reads_as_script_prose(statement):



    if statement.type == "labeled_statement":
        body = statement.child_by_field_name("body")
        return body is not None and _reads_as_script_prose(body)
    values = statement.named_children
    if statement.type == "return_statement":
        return len(values) == 1 and values[0].type == "identifier"
    if statement.type != "expression_statement" or len(values) != 1:
        return False
    if values[0].type in ("unary_expression", "await_expression", "yield_expression"):
        operands = values[0].named_children
        return len(operands) == 1 and operands[0].type == "identifier"
    return values[0].type in _SCRIPT_PROSE


def _is_script_skipped(parser, body):



    body = body.strip()
    if _SCRIPT_DIRECTIVE.match(body):
        return True
    root = parser.parse(body.encode("utf-8")).root_node
    return not root.has_error and any(not _reads_as_script_prose(s)
                                      for s in root.named_children if s.type != "comment")


def documents(comment):



    node = comment.next_named_sibling
    while node is not None and node.type in ("comment", "decorator"):
        node = node.next_named_sibling
    if node is not None and node.type == "export_statement":
        inner = [c for c in node.named_children if c.type not in ("comment", "decorator")]
        if inner and inner[0].type in _DEFAULT_DOCUMENTED:
            return True
        node = inner[0] if inner else None
    return node is not None and (node.type in _DOCUMENTED or _declares_functions(node))


def _declares_functions(node):

    if node.type not in ("lexical_declaration", "variable_declaration"):
        return False
    values = [d.child_by_field_name("value") for d in node.named_children
              if d.type == "variable_declarator"]
    return bool(values) and all(v is not None and v.type in _FUNCTION_VALUES for v in values)


def _block_unit(raw, start, row, line, documented):









    opening = _BLOCK_OPEN.match(raw).group(0)
    base, inner = start + len(opening), raw[len(opening):-2]
    bounds, position = [], 0
    for match in _BREAK.finditer(inner):
        bounds.append((position, match.start()))
        position = match.end()
    bounds.append((position, len(inner)))
    first, last = 0, len(bounds) - 1
    if last > 0 and not inner[slice(*bounds[0])].strip():
        first = 1
    if last > first and not inner[slice(*bounds[last])].strip():
        last -= 1
    pairs, texts, head = [], [], None
    for index in range(first, last + 1):
        a, b = bounds[index]
        source = inner[a:b]
        if index == 0:
            space = 1 if source.startswith(" ") and source.strip() else 0
            margin = line[:len(line) - len(line.lstrip(" \t"))]
            pairs.append((margin + " " * (len(opening) + space), ""))
            begin = a + space
            head = begin
        else:
            indent = source[:len(source) - len(source.lstrip(" \t"))]
            rest = source[len(indent):]
            prefix = ""
            if rest.startswith("*"):
                prefix = "*" + (" " if rest[1:].startswith(" ") and rest[1:].strip() else "")
            pairs.append((indent, prefix))
            begin = a + len(indent) + len(prefix)
            head = a + len(indent) if head is None else head
        end = a + len(source.rstrip(" \t")) if index == len(bounds) - 1 else b
        texts.append(inner[begin:end])
    body = "\n".join(texts)
    if not body.strip():
        return None
    kind = "docstring" if opening == "/**" and documented else "comment"
    return (base + head, base + end, kind, row + first, row + last, body,
            {"kind": "block_comment", "open": opening, "close": "*/", "lines": pairs}, None)


def _script_comments(script, text, lines):






    heads = set()
    groups, pending = [], []
    for node in walk(script.root):
        if node.type != "comment" or not _placed(node):
            continue
        start, end = script.offset(node.start_byte), script.offset(node.end_byte)
        raw, row = text[start:end], node.start_point[0] + 1
        line = lines[row - 1]
        if raw.startswith("/*"):
            opening = _BLOCK_OPEN.match(raw).group(0)
            if not _is_script_skipped(script.parser, raw[len(opening):-2]):
                unit = _block_unit(raw, start, row, line, documents(node))
                if unit is not None:
                    pending.append(unit)
                    if not text[text.rfind("\n", 0, start) + 1:start].strip():
                        heads.add(unit[0])
            continue
        marker = _SCRIPT_MARKER.match(raw).group(0)
        rest = raw[len(marker):]
        if _is_script_skipped(script.parser, rest):
            continue
        prefix = marker + (" " if rest.startswith(" ") and rest.strip() else "")
        entry = (row, start, end, line[:len(line) - len(line.lstrip(" \t\f"))], prefix,
                 raw[len(prefix):])
        trailing = bool(text[text.rfind("\n", 0, start) + 1:start].strip())
        if trailing or not groups or groups[-1][1] or groups[-1][0][-1][0] != row - 1:
            groups.append(([entry], trailing))
        else:
            groups[-1][0].append(entry)
    for entries, trailing in groups:
        if not trailing:
            heads.add(entries[0][1])
        pending.append((entries[0][1], entries[-1][2], "comment", entries[0][0], entries[-1][0],
                        "\n".join(entry[5] for entry in entries),
                        {"kind": "comment", "lines": [(e[3], e[4]) for e in entries]}, None))
    first = min((item for item in pending if item[0] in heads), key=lambda item: item[0],
                default=None)
    if first is not None and any(word in first[5] for word in _LICENSE):
        pending[pending.index(first)] = first[:7] + ("C147",)
    return pending


def _placed(node):

    parent = node.parent
    while parent is not None:
        if parent.is_error:
            return False
        parent = parent.parent
    return True


def _script_strings(script, text, fixture, pending, records):








    tag = "C148" if fixture else None
    for node in walk(script.root):
        if node.type not in ("string", "template_string") or not node.is_named:
            continue
        if not _placed(node):
            continue
        start, end = script.offset(node.start_byte) + 1, script.offset(node.end_byte) - 1
        key = node.parent.type == "pair" and node.parent.child_by_field_name("key") == node
        markup = (node.parent.type == "jsx_attribute"
                  or (node.parent.type == "jsx_expression"
                      and node.parent.parent.type == "jsx_attribute"))
        tagged = node.type == "template_string" and node.parent.type == "call_expression"
        protocol = key or markup or tagged or _is_class_list(node, text[start:end])
        kind = "C145" if protocol else _string_class("", text[start:end])
        if kind == "C145":
            records.append((None, start, end, "C145"))
        if kind == "prose":
            indent, closing, body = _layout(text[start:end], dedent=False)
            pending.append((start, end, "prose_string", node.start_point[0] + 1,
                            node.end_point[0] + 1, body,
                            {"kind": "prose_string", "indent": indent, "quote": text[start - 1],
                             "prefix": "", "closing_on_own_line": closing}, tag))
        elif fixture:
            records.append((None, start, end, "C148"))


def _is_class_list(node, inner):



    call = node.parent.parent if node.parent.type == "arguments" else None
    if call is not None and call.type == "call_expression":
        function = call.child_by_field_name("function")
        if function.type == "identifier" and _text(function) in _CLASS_CALLS:
            return True
    words = inner.split()
    return bool(words) and all(any(c == "-" or c.isdigit() for c in word) for word in words)


def _text(node):
    return node.text.decode("utf-8")


def exported_names(root):



    names = []
    for statement in root.named_children:
        if statement.type == "export_statement":
            names += _bindings(statement)
        elif statement.type == "expression_statement" and statement.named_children:
            names += _commonjs_names(statement.named_children[0])
    return list(dict.fromkeys(names))


def _bindings(node):

    names = []
    for child in node.named_children:
        if child.type in _NAMED_DECLARATIONS:
            name = child.child_by_field_name("name")
            names += [_text(name)] if name is not None else []
        elif child.type in ("lexical_declaration", "variable_declaration"):
            for declarator in child.named_children:
                target = declarator.child_by_field_name("name")
                if declarator.type == "variable_declarator" and target is not None:
                    names += [_text(n) for n in bound(target)]
        elif child.type == "export_clause":
            for specifier in child.named_children:
                name = (specifier.child_by_field_name("alias")
                        or specifier.child_by_field_name("name"))
                names += [_text(name)] if name is not None else []
        elif child.type == "ambient_declaration":
            names += _bindings(child)
    return names


def bound(pattern):


    if pattern is None:
        return
    if pattern.type in ("identifier", "shorthand_property_identifier_pattern"):
        yield pattern
    elif pattern.type in ("object_pattern", "array_pattern", "rest_pattern"):
        for child in pattern.named_children:
            yield from bound(child)
    elif pattern.type == "pair_pattern":
        yield from bound(pattern.child_by_field_name("value"))
    elif pattern.type in ("assignment_pattern", "object_assignment_pattern"):
        yield from bound(pattern.child_by_field_name("left"))
    elif pattern.type in ("required_parameter", "optional_parameter"):
        yield from bound(pattern.child_by_field_name("pattern"))


def _commonjs_names(expression):

    if expression.type != "assignment_expression":
        return []
    left, right = expression.child_by_field_name("left"), expression.child_by_field_name("right")
    if _text(left) == "module.exports":
        if right.type != "object":
            return []
        names = []
        for entry in right.named_children:
            if entry.type == "shorthand_property_identifier":
                names.append(_text(entry))
            elif entry.type in ("pair", "method_definition"):
                key = entry.child_by_field_name("key") or entry.child_by_field_name("name")
                names.append(_text(key).strip("\"'"))
        return names
    if (left.type == "member_expression"
            and _text(left.child_by_field_name("object")) in ("module.exports", "exports")):
        return [_text(left.child_by_field_name("property"))]
    return []


def _script_text(text, path, newline):



    document = Document(path=path, format=FORMAT, units=[], cannot_see=list(SCRIPT_CANNOT_SEE),
                        encoding="utf-8", newline=newline)
    script, refusal = parse_script(text, path)
    if script is None:
        document.cannot_see.append(refusal)
        return document
    if script.root.has_error:
        broken = next(n for n in walk(script.root) if n.is_error or n.is_missing)
        document.cannot_see.append(
            f"{path}: the parser found a syntax error at line {broken.start_point[0] + 1}, so "
            "the comments and strings it could place were read and the rest was not")
    lines = text.split("\n")
    posix = "/" + str(path).replace("\\", "/").lstrip("/")
    skipped = (any(d in posix for d in _SKIPPED_DIRS) or posix.endswith(".min.js")
               or any(p.match(lines[0].rstrip("\r")) for p in _SCRIPT_GENERATED))
    document.skipped = skipped
    document.protected_names = exported_names(script.root)
    records = []
    pending = _script_comments(script, text, lines)
    _script_strings(script, text, any(f in posix for f in _SCRIPT_FIXTURES), pending, records)
    return _finish(document, text, path, pending, records, skipped)


def _escape(body, quote, prefix):













    char, raw, single = quote[0], "r" in prefix, len(quote) == 1
    template = quote == "`"
    out, i = [], 0
    while i < len(body):
        if body[i] == "\\":
            if i + 1 == len(body):
                if raw:
                    raise ValueError("a raw string cannot end in a backslash")
                out.append("\\\\")
                i += 1
                continue
            step = 3 if body.startswith("\\\r\n", i) else 2
            out.append(body[i:i + step])
            i += step
            continue
        if template and body.startswith("${", i):
            out.append("\\${")
            i += 2
            continue
        if single and not template and (body[i] == "\n" or body.startswith("\r\n", i)):
            if raw:
                raise ValueError("a raw string in one quote cannot hold a line break")
            out.append("\\n")
            i += 2 if body[i] == "\r" else 1
            continue
        if body[i] != char:
            out.append(body[i])
            i += 1
            continue
        j = i
        while j < len(body) and body[j] == char:
            j += 1
        run = j - i
        escaped = len(quote) == 1 or run >= 3 or j == len(body)
        out.append(("\\" + char) * run if escaped else char * run)
        i = j
    return "".join(out)


def emit(source, unit, new_text):















    start, end = unit.span
    frame = unit.frame
    inside = source[start:end]
    newline = "\r\n" if "\r\n" in (inside if "\n" in inside else source) else "\n"
    if frame["kind"] in ("comment", "block_comment"):
        pairs = frame["lines"]
        pieces = []
        for i, line in enumerate(new_text.split("\n")):
            indent, prefix = pairs[min(i, len(pairs) - 1)]
            prefix = prefix if line else prefix.rstrip()
            pieces.append(prefix + line if i == 0 else newline + indent + prefix + line)
        body = "".join(pieces)
        if frame["kind"] == "block_comment" and frame["close"] in body:
            raise ValueError("a block comment cannot hold the delimiter that closes it")
    else:
        quote = frame["quote"]
        if frame["kind"] == "prose_string" and quote in ("'", '"'):
            quote = _quote_for(new_text, quote)
        body = _escape(_render(new_text, frame["indent"], frame["closing_on_own_line"], newline),
                       quote, frame["prefix"])
        if quote != frame["quote"]:
            start, end, body = start - 1, end + 1, quote + body + quote
    return source[:start] + body + source[end:]


def _quote_for(text, quote):






    other = "'" if quote == '"' else '"'
    own, i = 0, 0
    while i < len(text):
        if text[i] == "\\":
            i += 2
            continue
        own += text[i] == quote
        i += 1
    return other if own > text.count(other) else quote
